#!/usr/bin/env python3
"""Export the public portal registry from Vizzie's compliance matrix.

Usage:
    python3 scripts/build.py /path/to/portal-compliance-matrix.json

Writes data/portals.json and data/portals.csv, and rewrites the generated
figures block in README.md. Internal-only fields (operational notes, crawl
rates, per-dataset overrides) are excluded; everything published here is
observable from the portals themselves.
"""
import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

PUBLIC_FIELDS = [
    "id", "label", "country", "region", "city", "platform", "connector",
    "base_url", "tos_url", "default_licence", "licence_source",
    "observed_licences", "undeclared_share", "auth",
]

BEGIN = "<!-- figures:begin (generated by scripts/build.py) -->"
END = "<!-- figures:end -->"


def main(matrix_path: str) -> None:
    matrix = json.loads(Path(matrix_path).read_text())
    portals = []
    for p in matrix["portals"]:
        portals.append({k: p.get(k) for k in PUBLIC_FIELDS if p.get(k) is not None})
    portals.sort(key=lambda p: (p["country"], p["id"]))

    out = {
        "name": "open-data-portal-registry",
        "description": (
            "Open data portals observed by Vizzie (vizzie.org): platform, API "
            "type, terms URL, declared licences and the measured share of "
            "datasets with no declared licence."
        ),
        "licence": "CC BY 4.0",
        "observed_as_at": matrix.get("generated"),
        "portal_count": len(portals),
        "country_count": len({p["country"] for p in portals}),
        "portals": portals,
    }
    (ROOT / "data" / "portals.json").write_text(json.dumps(out, indent=1, ensure_ascii=False) + "\n")

    flat_fields = [f for f in PUBLIC_FIELDS if f != "observed_licences"] + [
        "declared_licences", "dataset_count_observed",
    ]
    with (ROOT / "data" / "portals.csv").open("w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=flat_fields)
        w.writeheader()
        for p in portals:
            row = {k: p.get(k, "") for k in flat_fields}
            obs = p.get("observed_licences") or {}
            row["declared_licences"] = "; ".join(
                f"{k}:{v}" for k, v in sorted(obs.items(), key=lambda kv: -kv[1])
            )
            row["dataset_count_observed"] = sum(obs.values()) or ""
            w.writerow(row)

    # Figures in the README are generated, never hand-typed.
    by_platform = {}
    for p in portals:
        by_platform[p["platform"]] = by_platform.get(p["platform"], 0) + 1
    singles = sorted(name for name, n in by_platform.items() if n == 1)
    platform_rows = "\n".join(
        f"| {name} | {n} |"
        for name, n in sorted(by_platform.items(), key=lambda kv: -kv[1])
        if n > 1
    )
    if singles:
        platform_rows += f"\n| Bespoke single-portal APIs ({', '.join(singles[:4])}, …) | {len(singles)} |"
    block = (
        f"{BEGIN}\n"
        f"**{out['portal_count']} portals** across **{out['country_count']} countries and regions**, "
        f"observed as at {out['observed_as_at']}.\n\n"
        f"| Platform | Portals |\n| --- | --- |\n{platform_rows}\n"
        f"{END}"
    )
    readme = (ROOT / "README.md").read_text()
    i, j = readme.index(BEGIN), readme.index(END)
    (ROOT / "README.md").write_text(readme[:i] + block + readme[j + len(END):])
    print(f"wrote {out['portal_count']} portals, {out['country_count']} countries")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
